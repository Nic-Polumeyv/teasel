use crate::interner::StrId;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Token {
	pub kind: TokenKind,
	pub start: u32,
	pub end: u32,
	pub newline_before: bool,
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum TokenKind {
	Eof,
	Ident {
		name: StrId,
		escaped: bool,
	},
	PrivateName(StrId),
	Keyword(Keyword),
	Number {
		value: f64,
		legacy_octal: bool,
	},
	BigInt,
	String {
		value: StrId,
		octal: bool,
	},
	Template {
		cooked: Option<StrId>,
		raw: StrId,
		tail: bool,
	},
	RegExp {
		pattern: StrId,
		flags: StrId,
	},

	BraceL,
	BraceR,
	ParenL,
	ParenR,
	BracketL,
	BracketR,
	Semi,
	Comma,
	Dot,
	Ellipsis,
	Question,
	QuestionDot,
	Colon,
	Arrow,
	Backquote,
	DollarBraceL,
	At,

	Eq,
	PlusEq,
	MinusEq,
	StarEq,
	SlashEq,
	PercentEq,
	StarStarEq,
	LtLtEq,
	GtGtEq,
	GtGtGtEq,
	AmpEq,
	PipeEq,
	CaretEq,
	AmpAmpEq,
	PipePipeEq,
	QuestionQuestionEq,

	EqEq,
	BangEq,
	EqEqEq,
	BangEqEq,
	Lt,
	Gt,
	LtEq,
	GtEq,
	LtLt,
	GtGt,
	GtGtGt,
	Plus,
	Minus,
	Star,
	Slash,
	Percent,
	StarStar,
	Amp,
	Pipe,
	Caret,
	AmpAmp,
	PipePipe,
	QuestionQuestion,
	Bang,
	Tilde,
	PlusPlus,
	MinusMinus,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Keyword {
	Break,
	Case,
	Catch,
	Class,
	Const,
	Continue,
	Debugger,
	Default,
	Delete,
	Do,
	Else,
	Export,
	Extends,
	False,
	Finally,
	For,
	Function,
	If,
	Import,
	In,
	Instanceof,
	New,
	Null,
	Return,
	Super,
	Switch,
	This,
	Throw,
	True,
	Try,
	Typeof,
	Var,
	Void,
	While,
	With,
}

impl Keyword {
	pub fn from_word(word: &str) -> Option<Keyword> {
		use Keyword::*;
		Some(match word {
			"break" => Break,
			"case" => Case,
			"catch" => Catch,
			"class" => Class,
			"const" => Const,
			"continue" => Continue,
			"debugger" => Debugger,
			"default" => Default,
			"delete" => Delete,
			"do" => Do,
			"else" => Else,
			"export" => Export,
			"extends" => Extends,
			"false" => False,
			"finally" => Finally,
			"for" => For,
			"function" => Function,
			"if" => If,
			"import" => Import,
			"in" => In,
			"instanceof" => Instanceof,
			"new" => New,
			"null" => Null,
			"return" => Return,
			"super" => Super,
			"switch" => Switch,
			"this" => This,
			"throw" => Throw,
			"true" => True,
			"try" => Try,
			"typeof" => Typeof,
			"var" => Var,
			"void" => Void,
			"while" => While,
			"with" => With,
			_ => return None,
		})
	}

	pub fn as_str(self) -> &'static str {
		use Keyword::*;
		match self {
			Break => "break",
			Case => "case",
			Catch => "catch",
			Class => "class",
			Const => "const",
			Continue => "continue",
			Debugger => "debugger",
			Default => "default",
			Delete => "delete",
			Do => "do",
			Else => "else",
			Export => "export",
			Extends => "extends",
			False => "false",
			Finally => "finally",
			For => "for",
			Function => "function",
			If => "if",
			Import => "import",
			In => "in",
			Instanceof => "instanceof",
			New => "new",
			Null => "null",
			Return => "return",
			Super => "super",
			Switch => "switch",
			This => "this",
			Throw => "throw",
			True => "true",
			Try => "try",
			Typeof => "typeof",
			Var => "var",
			Void => "void",
			While => "while",
			With => "with",
		}
	}
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Comment {
	pub block: bool,
	pub start: u32,
	pub end: u32,
}
