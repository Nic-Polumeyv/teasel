// Regenerates src/lexer/unicode.rs and the bindings' identifier.js from the Unicode Character Database.
// Usage: bun scripts/unicode.js [version]

const version = process.argv[2] ?? '17.0.0';
const url = `https://www.unicode.org/Public/${version}/ucd/DerivedCoreProperties.txt`;
const text = await (await fetch(url)).text();

function ranges(property) {
	const out = [];
	for (const line of text.split('\n')) {
		const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/);
		if (!m || m[3] !== property) continue;
		const start = parseInt(m[1], 16);
		const end = m[2] ? parseInt(m[2], 16) : start;
		if (end < 0x80) continue;
		out.push([Math.max(start, 0x80), end]);
	}
	out.sort((a, b) => a[0] - b[0]);
	const merged = [];
	for (const r of out) {
		const last = merged.at(-1);
		if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1]);
		else merged.push(r);
	}
	return merged;
}

function table(name, rs) {
	const rows = [];
	for (let i = 0; i < rs.length; i += 4) {
		rows.push('\t' + rs.slice(i, i + 4).map(([a, b]) => `(0x${a.toString(16)}, 0x${b.toString(16)})`).join(', ') + ',');
	}
	return `static ${name}: &[(u32, u32)] = &[\n${rows.join('\n')}\n];\n`;
}

const start = ranges('ID_Start');
const cont = ranges('ID_Continue');

const src = `// Generated by scripts/unicode.js from Unicode ${version}. Do not edit.

${table('ID_START', start)}
${table('ID_CONTINUE', cont)}
fn lookup(table: &[(u32, u32)], c: u32) -> bool {
	table
		.binary_search_by(|&(lo, hi)| {
			if c < lo {
				std::cmp::Ordering::Greater
			} else if c > hi {
				std::cmp::Ordering::Less
			} else {
				std::cmp::Ordering::Equal
			}
		})
		.is_ok()
}

pub(crate) fn is_id_start(c: char) -> bool {
	if c.is_ascii() {
		return c.is_ascii_alphabetic();
	}
	lookup(ID_START, c as u32)
}

pub(crate) fn is_id_continue(c: char) -> bool {
	if c.is_ascii() {
		return c.is_ascii_alphanumeric();
	}
	lookup(ID_CONTINUE, c as u32)
}
`;

await Bun.write(new URL('../src/lexer/unicode.rs', import.meta.url), src);

function flat(rs) {
	const rows = [];
	for (let i = 0; i < rs.length; i += 8) {
		rows.push('\t' + rs.slice(i, i + 8).map(([a, b]) => `0x${a.toString(16)}, 0x${b.toString(16)}`).join(', ') + ',');
	}
	return rows.join('\n');
}

const js = `// Generated by scripts/unicode.js from Unicode ${version}. Do not edit.
// The parser's own identifier tables, so a host tokenizing around embedded JavaScript agrees with
// it whatever Unicode its engine has. Each table is a flat list of inclusive ranges.
const ID_START = [
${flat(start)}
];
const ID_CONTINUE = [
${flat(cont)}
];

/** @param {number[]} table @param {number} code */
function lookup(table, code) {
	let lo = 0;
	let hi = table.length >> 1;
	while (lo < hi) {
		const mid = (lo + hi) >> 1;
		if (code < table[mid * 2]) hi = mid;
		else if (code > table[mid * 2 + 1]) lo = mid + 1;
		else return true;
	}
	return false;
}

/** Whether a code point can start an identifier. @param {number} code */
export function isIdentifierStart(code) {
	if (code < 128) return (code >= 65 && code <= 90) || (code >= 97 && code <= 122) || code === 36 || code === 95;
	return lookup(ID_START, code);
}

/** Whether a code point can continue an identifier. @param {number} code */
export function isIdentifierChar(code) {
	if (code < 128) return (code >= 65 && code <= 90) || (code >= 97 && code <= 122) || (code >= 48 && code <= 57) || code === 36 || code === 95;
	return code === 0x200c || code === 0x200d || lookup(ID_CONTINUE, code);
}
`;
await Bun.write(new URL('../bindings/node/identifier.js', import.meta.url), js);
await Bun.write(new URL('../bindings/wasm/identifier.js', import.meta.url), js);
console.log(`ID_Start ${start.length} ranges, ID_Continue ${cont.length} ranges`);
